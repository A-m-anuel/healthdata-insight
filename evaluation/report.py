"""Render evaluation results (``results.json``) as Markdown tables (``results.md``)."""

from __future__ import annotations


def _pct(value: float | None, digits: int = 1) -> str:
    return "n/a" if value is None else f"{100 * value:.{digits}f}%"


def _num(value, digits: int = 1) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:,.{digits}f}"
    return f"{value:,}"


def _key(key: str) -> str:
    """Composite keys are stored as 'a|b|c'; a pipe would break a Markdown table."""
    return key.replace("|", " / ")


def _table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(" --- " for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _prf_row(label: str, m: dict) -> list:
    return [label, _num(m["tp"]), _num(m["fp"]), _num(m["fn"]), _num(m.get("tn")), _pct(m["precision"]),
            _pct(m["recall"]), _pct(m["f1"])]


PRF_HEADERS = ["", "TP", "FP", "FN", "TN", "Precision", "Recall", "F1"]


def render_markdown(r: dict) -> str:
    meta, env = r["meta"], r["meta"]["environment"]
    out: list[str] = ["# Evaluation results (generated)", "",
                      "Generated by `python -m evaluation.run_evaluation`. Do not edit by hand.", ""]

    out += ["## Run", "", _table(["Item", "Value"], [
        ["Started / finished (UTC)", f"{meta['started']} / {meta['finished']}"],
        ["Dataset", f"{meta['data_url']}"],
        ["Dataset SHA-256", f"`{meta['data_sha256']}`"],
        ["Reference date (ages, future-date checks)", meta["reference_date"]],
        ["Seed", meta["seed"]],
        ["Batch size (patients)", meta["batch_size"]],
        ["Python / SQLite / R", f"{env['python']} / {env['sqlite']} / {env['r'] or 'not available'}"],
        ["Packages", ", ".join(f"{k} {v}" for k, v in env["packages"].items())],
        ["Machine", f"{env['processor']}, {env['logical_cpus']} logical CPUs, {env['total_ram_gb']} GB RAM, "
                    f"{env['platform']}"],
        ["Free commit memory at start", f"{env['free_commit_gb_at_start']} GB"],
    ]), ""]

    d = r["dataset"]
    out += ["## Dataset", "", f"{d['patients']:,} patients in {d['batches']} batches; {d['resources']:,} resources "
            f"({d['in_scope']:,} in scope); {d['bytes'] / 1e6:,.1f} MB of JSON.", "",
            _table(["Resource type", "Count"], [[k, _num(v)] for k, v in d["by_type"].items()]), ""]

    b = r["baseline"]
    out += ["## Baseline: unmodified Synthea data", "", _table(["Measure", "Value"], [
        ["Validation errors", _num(b["errors"])],
        ["Invalid records", _num(b["invalid_records"])],
        ["Warnings", _num(b["warnings"])],
        ["Completeness", _pct(b["completeness"], 2)],
        ["Records flagged as duplicates", _num(b["duplicates_flagged"])],
        ["Parse issues", _num(b["parse_issues"])],
        *[[f"{dim.capitalize()} score", _pct(v, 2)] for dim, v in b["dimension_scores"].items()],
    ]), "", "Issues by severity, code, and resource type (excluding the per-type out-of-scope notes):", "",
        _table(["Severity / code / type", "Count"], [[_key(k), _num(v)] for k, v in b["issues_by_code"].items()]),
        ""]
    if b["error_examples"]:
        out += ["Error examples:", "", *[f"- {e}" for e in b["error_examples"]], ""]

    v = r["validation_defects"]
    out += ["## E1. FHIR validation accuracy (injected structure and validity defects)", "",
            _table(["Defect", "Injected", "Expected code reported", "Detection rate", "Record flagged invalid",
                    "Other codes on record"],
                   [[n, _num(s["injected"]), _num(s.get("detected", 0)), _pct(s["detection_rate"]),
                     _num(s.get("flagged_invalid", 0)), _num(s.get("other_codes", 0))]
                    for n, s in v["per_defect"].items()]), "",
            f"Expected issue code reported: {_num(v['detected_expected_code'])} of {_num(v['injected'])} "
            f"({_pct(v['detection_rate'])}). Each defect type was injected and validated in its own pass.", "",
            "Valid/invalid classification of records, summed over the passes (injected = should be invalid; "
            "all other records in the pass = should be valid):", "", _table(PRF_HEADERS + ["Accuracy", "Specificity"],
                                     [_prf_row("Records", v["record_classification"])
                                      + [_pct(v["record_classification"]["accuracy"], 3),
                                         _pct(v["record_classification"]["specificity"], 3)]]), ""]
    m = r["malformed_lines"]
    if m:
        out += ["Malformed NDJSON lines (batch 0):", "", _table(["Line defect", "Injected", "Reported"],
                [[k, m["injected"][k], m["detected"][k]] for k in m["injected"]]), "",
                f"Resources read: {m['resources_read']} (expected {m['expected_resources_read']}).", ""]

    q = r["quality_defects"]
    c = q["completeness_check"]
    out += ["## E3. Data-quality defect detection (injected completeness and consistency defects)", "",
            _table(["Defect", "Injected", "Expected code reported", "Detection rate"],
                   [[n, _num(s["injected"]), _num(s.get("detected", 0)), _pct(s["detection_rate"])]
                    for n, s in q["per_defect"].items()]), "",
            f"Expected issue code reported: {_num(q['detected_expected_code'])} of {_num(q['injected'])} "
            f"({_pct(q['detection_rate'])}). Clean records newly flagged invalid: {_num(q['clean_flagged_invalid'])} "
            f"of {_num(q['clean_records'])}.", "",
            f"Completeness accounting: across the isolated passes, the missing-field count rose by "
            f"{_num(c['missing_fields_increase'])} for {_num(c['completeness_defects_injected'])} injected missing "
            f"fields (exact match in {c['passes_matching_exactly']} of {c['passes']} passes).", "",
            _table(["Dimension", "Mean score before", "Mean score after"],
                   [[dim, _pct(s["before_mean"] / 100, 2) if s["before_mean"] is not None else "n/a",
                     _pct(s["after_mean"] / 100, 2) if s["after_mean"] is not None else "n/a"]
                    for dim, s in q["score_change"].items()]), ""]

    dup = r["duplicates"]
    out += ["## E4. Duplicate detection", "",
            _table(["Case", "Truly a duplicate", "Injected", "Flagged", "Flag rate", "Expected code"],
                   [[n, "yes" if s["is_duplicate"] else "no", _num(s["injected"]), _num(s["flagged"]),
                     _pct(s["flag_rate"]), _num(s.get("expected_code", 0))] for n, s in dup["per_case"].items()]),
            "", _table(PRF_HEADERS, [_prf_row("All cases", dup["all_cases"]),
                                     _prf_row("Excluding the fuzzy-match case", dup["excluding_fuzzy_case"])]),
            "", "Flagged in the unmodified data (within each batch):", "",
            _table(["Type / code", "Count"], [[_key(k), _num(v)] for k, v in dup["baseline_flagged"].items()]), ""]

    p = r["phi"]
    out += ["## E2. PHI detection (labelled locations)", "",
            _table(PRF_HEADERS, [_prf_row("All locations", p["overall"]),
                                 *[_prf_row(scope, m) for scope, m in p["by_scope"].items()]]), "",
            f"Precision counting only high- and medium-severity findings: {_pct(p['precision_high_medium_only'])}. "
            f"Findings outside the labelled locations (counted as false positives above): "
            f"{_num(sum(p['unexpected_findings'].values()))}.", "",
            _table(["Location type", "PHI (ground truth)", "Locations", "Flagged", "Flag rate"],
                   [[k, "yes" if s["is_phi"] else "no", _num(s["locations"]), _num(s["flagged"]),
                     _pct(s["flagged"] / s["locations"] if s["locations"] else None)]
                    for k, s in p["by_location_type"].items()]), "",
            _table(["Finding severity / truth", "Findings"],
                   [[_key(k), _num(v)] for k, v in p["findings_by_severity"].items()]),
            ""]
    if p["unexpected_findings"]:
        out += [_table(["Unexpected finding (rule / path)", "Count"],
                       [[_key(k), _num(v)] for k, v in p["unexpected_findings"].items()]), ""]
    out += [f"Detector time: {p['detector_seconds']:.2f} s for {p['resources_scanned']:,} resources.", ""]

    perf = r["performance"]
    bm = perf["batch_mode"]
    out += ["## E5/E6. Processing time and throughput", "",
            f"Batch mode (all {bm['patients']:,} patients, {bm['resources']:,} resources, batches of "
            f"{meta['batch_size']}): ingest {bm['ingest_seconds']:.1f} s + processing {bm['pipeline_seconds']:.1f} s "
            f"= {bm['end_to_end_seconds']:.1f} s; {bm['resources_per_second_end_to_end']:,.0f} resources/s end to end, "
            f"{bm['resources_per_second_pipeline']:,.0f} resources/s for processing (validation, quality, PHI scan, "
            f"analytics, R, persistence). R status: {', '.join(bm['r_status'])}.", ""]
    if perf["single_process_series"]:
        stages = list(perf["single_process_series"][0]["median_stage_seconds"])
        out += ["Single process (median of repeats; fresh process per run):", "",
                _table(["Patients", "Resources", "Repeats", *[f"{s} (s)" for s in stages], "End to end (s)",
                        "Resources/s", "Peak commit (MB)", "Peak working set (MB)"],
                       [[_num(s["patients"]), _num(s["resources"]), s["repeats"],
                         *[f"{s['median_stage_seconds'][st]:.2f}" for st in stages],
                         f"{s['median_end_to_end_seconds']:.1f}", _num(s["resources_per_second_end_to_end"], 0),
                         _num(s["peak_commit_mb_max"], 0), _num(s["peak_working_set_mb_max"], 0)]
                        for s in perf["single_process_series"]]), ""]
    if perf["skipped"]:
        out += ["Skipped single-process runs:", "", *[f"- {json_line(s)}" for s in perf["skipped"]], ""]

    out += ["## E7. Sanitization", ""]
    for name, s in r["sanitization"].items():
        leak_rows = [[k, _num(s["leak_checks"].get(k, 0)), _num(s["leaks"].get(k, 0))] for k in s["leak_checks"]]
        out += [f"### {name} settings", "", f"`{json_line(s['settings'])}`", "", _table(["Measure", "Value"], [
            ["Resources in / out", f"{_num(s['resources_in'])} / {_num(s['resources_out'])}"],
            ["Time (sanitize + validate + re-scan)", f"{s['seconds']:.1f} s"],
            ["Validation errors before / after", f"{_num(s['errors_before'])} / {_num(s['errors_after'])}"],
            ["New error types", ", ".join(s["new_error_codes"]) or "none"],
            ["Reference issues before / after",
             f"{_num(s['reference_issues_before'])} / {_num(s['reference_issues_after'])}"],
            ["Remaining high-risk findings", _num(s["residual_high"])],
            ["Round trip (output re-parsed)", json_line(s["round_trip"]) if s["round_trip"] else "not run"],
        ]), "", "Remaining findings by rule and severity:", "",
            _table(["Rule / severity", "Findings"], [[_key(k), _num(v)] for k, v in s["residual_findings"].items()])
            if s["residual_findings"] else "None.", "",
            "Original identifying values searched for in each patient's sanitized resources:", "",
            _table(["Value type", "Values checked", "Still present"], leak_rows), "",
            "Where the remaining values were found (value type / resource type: resources containing it):", "",
            _table(["Value type / resource type", "Resources"],
                   [[_key(k), _num(v)] for k, v in s["leak_locations"].items()]) if s["leak_locations"] else "None.",
            "",
            "Changes made:", "", _table(["Change", "Count"], [[k, _num(v)] for k, v in s["actions"].items()]), ""]

    i = r["information"]
    out += ["## E8. Analytical information preserved after sanitization", "", _table(["Measure", "Value"], [
        ["Records raw vs analytical (patients)", " vs ".join(_num(x) for x in i["records_raw_vs_analytic"]["patients"])],
        ["Records raw vs analytical (conditions)", " vs ".join(_num(x) for x in i["records_raw_vs_analytic"]["conditions"])],
        ["Records raw vs analytical (observations)",
         " vs ".join(_num(x) for x in i["records_raw_vs_analytic"]["observations"])],
        ["Gender distribution identical", i["gender_identical"]],
        ["State distribution identical", i["state_identical"]],
        ["Age group agreement (birth year vs exact birth date)", _pct(i["age_group_agreement"], 2)],
        ["Age-group distribution total variation distance", _pct(i["age_group_distribution_tvd"], 2)],
        ["Condition codes (raw / analytical)", " / ".join(_num(x) for x in i["condition_codes"])],
        ["Max prevalence difference", f"{i['max_prevalence_difference_pct_points']:.4f} percentage points"],
        ["Numeric observation series (raw / analytical)", " / ".join(_num(x) for x in i["observation_series"])],
        ["Series with identical n", _num(i["observation_series_same_n"])],
        ["Max absolute difference in series mean / SD",
         f"{_num(i['max_abs_mean_difference'], 6)} / {_num(i['max_abs_sd_difference'], 6)}"],
        ["Observation counts per month identical", i["observation_months_identical"]],
        ["Condition onsets per month identical", i["condition_months_identical"]],
        ["Linked conditions raw / analytical", " / ".join(_num(x) for x in i["linked_conditions"])],
        ["Linked observations raw / analytical", " / ".join(_num(x) for x in i["linked_observations"])],
        ["Distinct cities / postal codes in raw data (none kept)",
         f"{_num(i['distinct_cities_raw'])} / {_num(i['distinct_postal_codes_raw'])}"],
        ["Distinct observation days raw vs months kept",
         f"{_num(i['distinct_observation_days_raw'])} vs {_num(i['distinct_observation_months_analytic'])}"],
    ]), "", _table(["Age group", "Raw (exact age)", "Analytical (birth year)"],
                   [[g, _num(i["age_group_raw_exact"].get(g, 0)), _num(i["age_group_analytic"].get(g, 0))]
                    for g in sorted(set(i["age_group_raw_exact"]) | set(i["age_group_analytic"]),
                                    key=lambda g: int(g.split("-")[0].rstrip("+")))]), ""]
    return "\n".join(out) + "\n"


def json_line(value) -> str:
    import json

    return json.dumps(value, sort_keys=True)
